const { withProjectBuildGradle } = require('@expo/config-plugins');
const path = require('node:path');

const NOTIFEE_REPOSITORY = 'notifee/react-native/android/libs';

/**
 * Notifee 9 bundles app.notifee:core in its local Android Maven repository.
 * Expo/RN autolinking adds the module, but this repository is not consistently
 * applied to the generated app project, so make it explicit at the root.
 *
 * The path is resolved here rather than hardcoded as `$rootDir/../node_modules`:
 * in this workspace the installer hoists @notifee/react-native to the repo root,
 * so `apps/mobile/node_modules/@notifee` does not exist and Gradle fails with
 * "Could not find any matches for app.notifee:core:+". require.resolve finds it
 * wherever it actually landed, hoisted or not.
 */
module.exports = function withNotifeeMaven(config) {
  return withProjectBuildGradle(config, (modConfig) => {
    if (modConfig.modResults.language !== 'groovy') {
      throw new Error('with-notifee-maven requires a Groovy Android build.gradle');
    }

    if (modConfig.modResults.contents.includes(NOTIFEE_REPOSITORY)) {
      return modConfig;
    }

    const projectRoot = modConfig.modRequest.projectRoot;
    const notifeePackage = require.resolve('@notifee/react-native/package.json', {
      paths: [projectRoot],
    });
    // Relative to android/, not absolute: EAS and every other machine check out
    // to a different prefix, and this file is regenerated by prebuild anyway.
    const libs = path
      .relative(path.join(projectRoot, 'android'), path.join(path.dirname(notifeePackage), 'android', 'libs'))
      .split(path.sep)
      .join('/');

    modConfig.modResults.contents += `\n\nallprojects {\n  repositories {\n    maven { url "$rootDir/${libs}" }\n  }\n}\n`;
    return modConfig;
  });
};
